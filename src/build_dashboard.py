"""Build a factual, read-only dashboard from STAMP artifacts."""
import html,json,pathlib
from pine_parity import signals
ROOT=pathlib.Path(__file__).resolve().parents[1]
def build(root=ROOT):
    def read(path):
        try:return json.loads((root/"data"/path).read_text())
        except (OSError,ValueError):return {}
    latest=read("latest.json");health=read("workflow_health.json")
    learning=read("learning_controller.json");score=read("forecast_scorecard.json")
    price=(latest.get("raw",{}).get("mexc",{}).get("ticker",{}).get("data") or {}).get("lastPrice","unknown")
    fields={"STAMP price (MEXC)":price,"Market observation UTC":latest.get("raw",{}).get("collected_at_utc"),
        "Workflow trigger":health.get("event_name"),"Workflow successful":health.get("pipeline_passed"),
        "Workflow observed UTC":health.get("timestamp_utc"),"Learning status":learning.get("status"),
        "Champion":learning.get("champion") or "none","Forecasts":score.get("forecasts_total"),
        "Evaluated outcomes":score.get("evaluated_total")}
    try:candles=json.loads((root/"data"/"candles"/"1h.json").read_text())
    except (OSError,ValueError):candles=[]
    parity=signals(candles,"1h")
    fields["Pine-compatible EMA crossover status"]=parity["status"]
    fields["Confirmed EMA crossover events"]=len(parity["events"])
    fields["Latest EMA crossover"]=parity["events"][-1]["signal"] if parity["events"] else "none"
    items="".join("<dt>"+html.escape(k)+"</dt><dd>"+html.escape(str(v))+"</dd>" for k,v in fields.items())
    models="".join("<tr><td>"+html.escape(k)+"</td><td>"+html.escape(str(v.get("mae")))+"</td><td>"+html.escape(str(v.get("skill_vs_zero")))+"</td></tr>" for k,v in learning.get("challengers",{}).items())
    page=("<!doctype html><html lang='en'><meta charset='utf-8'><meta name='viewport' content='width=device-width,initial-scale=1'>"
      "<title>STAMP Research Dashboard</title><style>body{font:16px system-ui;max-width:850px;margin:2em auto;padding:1em;background:#111827;color:#e5e7eb}"
      "dt{color:#93c5fd;margin-top:1em}dd{margin:0}table{width:100%;border-collapse:collapse}td,th{padding:9px;border-bottom:1px solid #475569;text-align:left}</style>"
      "<h1>STAMP Research Dashboard</h1><p>Read-only archived research. Not live trading data or financial advice.</p><dl>"+items+"</dl>"
      "<h2>Walk-forward model comparison</h2><table><tr><th>Model</th><th>MAE</th><th>Skill vs zero baseline</th></tr>"+models+"</table>"
      "<p>Generated by GitHub Actions from recorded evidence. A blank champion means no model met the validation threshold.</p></html>")
    out=root/"dashboard"/"index.html";out.parent.mkdir(parents=True,exist_ok=True)
    out.write_text(page,encoding="utf-8");return out
if __name__=="__main__":print(build())
